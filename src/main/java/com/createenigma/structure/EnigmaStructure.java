package com.createenigma.structure;

import java.io.InputStream;
import java.util.ArrayList;
import java.util.List;

import com.createenigma.CreateEnigma;
import com.createenigma.registry.CEBlocks;
import com.mojang.logging.LogUtils;
import com.simibubi.create.AllBlocks;
import com.simibubi.create.content.kinetics.base.DirectionalKineticBlock;

import org.slf4j.Logger;

import net.minecraft.core.BlockPos;
import net.minecraft.core.HolderGetter;
import net.minecraft.core.Vec3i;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.ListTag;
import net.minecraft.nbt.NbtAccounter;
import net.minecraft.nbt.NbtIo;
import net.minecraft.nbt.NbtUtils;
import net.minecraft.nbt.Tag;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.Rotation;
import net.minecraft.world.level.block.state.BlockState;

/**
 * The Enigma machine's shape, read once from the structure template this mod ships.
 *
 * <p>The template is generated by {@code tools/PrepareEnigmaStructure.java} from Create's Ponder
 * capture, and lives at {@code data/create_enigma/structure/mojang_enigma.nbt}. The same file is
 * what {@code /place template create_enigma:mojang_enigma} places, so the shape that gets built
 * and the shape that gets recognised provably come from one source.
 *
 * <p><b>Loaded from the classpath, not the datapack resource manager.</b> That keeps the check
 * independent of resource reloads and of datapacks that might override the template - at the cost
 * of not honouring such an override. If the template ever becomes datapack-tunable, this is the
 * place to change.
 */
public final class EnigmaStructure {

    private static final Logger LOGGER = LogUtils.getLogger();

    /**
     * The template's id: exactly what {@code /place template} takes and what its tab completion
     * lists. The classpath location below is derived from it, so the id the command resolves and
     * the file this mod reads can never drift apart.
     */
    public static final ResourceLocation TEMPLATE_ID =
            ResourceLocation.fromNamespaceAndPath(CreateEnigma.MOD_ID, "mojang_enigma");

    private static final String RESOURCE =
            "/data/" + TEMPLATE_ID.getNamespace() + "/structure/" + TEMPLATE_ID.getPath() + ".nbt";

    private static EnigmaStructure instance;
    private static boolean loadAttempted;

    /** One block of the machine, at its offset from the template's own corner. */
    public record Entry(BlockPos offset, BlockState state) {}

    /**
     * Which state of the machine is being talked about.
     *
     * <p>All three are derived from the one template, so they can never disagree about anything
     * except the three changes in {@link #derive}.
     */
    public enum Generation {
        /**
         * 一代 / what a survival player builds: a chest at the anchor, six disguised motors, and no
         * seventh. This is what the wrench reads.
         */
        PRIMAL,

        /**
         * The same machine once the chest has become the core: core at the anchor, six motors.
         *
         * <p><b>This is the one the core validates itself against</b>, and it has to exist as its own
         * state rather than reusing {@link #PRIMAL} - the core is standing where the chest template
         * expects a chest, so the core would fail a check against its own first generation.
         */
        ASSEMBLED,

        /** The machine as it was originally built: core, and all seven motors. */
        COMPLETE
    }

    /**
     * The motor Create's own ponder never reveals, at {@code (6, 0, 3)} in this template's
     * coordinates.
     *
     * <p>It is a real part of the machine - both Mojang's trailer and Create's show it - so the
     * complete template keeps it. It is left out of the first generation on purpose: a player can
     * only build what they were shown, and the ponder shows six motors. It gets added later, once
     * there is a reason to doubt the thing that showed them.
     */
    public static final BlockPos DISPUTED_MOTOR = new BlockPos(6, 0, 3);

    private final Vec3i size;
    private final List<Entry> entries;
    private final List<Entry> primalEntries;
    private final List<Entry> assembledEntries;
    private final BlockPos coreOffset;

    private EnigmaStructure(Vec3i size, List<Entry> entries, List<Entry> primalEntries,
                            List<Entry> assembledEntries, BlockPos coreOffset) {
        this.size = size;
        this.entries = entries;
        this.primalEntries = primalEntries;
        this.assembledEntries = assembledEntries;
        this.coreOffset = coreOffset;
    }

    /** The template's dimensions. */
    public Vec3i size() {
        return size;
    }

    /** Every non-air block of the machine, in template coordinates. */
    public List<Entry> entries() {
        return entries;
    }

    /** The blocks of the given state, in template coordinates. */
    public List<Entry> entries(Generation generation) {
        return switch (generation) {
            case PRIMAL -> primalEntries;
            case ASSEMBLED -> assembledEntries;
            case COMPLETE -> entries;
        };
    }

    /** What stands at the anchor: the core, except in the state the player builds first. */
    public static BlockState anchorState(Generation generation) {
        return generation == Generation.PRIMAL
                ? Blocks.CHEST.defaultBlockState()
                : CEBlocks.ENIGMA_CORE.get().defaultBlockState();
    }

    /** Where the anchor block sits inside the template. The same position in either generation. */
    public BlockPos coreOffset() {
        return coreOffset;
    }

    /**
     * Turns the world position of a core block into the template's own origin, so that
     * {@code origin.offset(entry.offset())} addresses the world.
     */
    public BlockPos originFor(BlockPos corePos) {
        return corePos.subtract(coreOffset);
    }

    /**
     * Where a template offset ends up once the machine is turned.
     *
     * <p><b>Rotation is around the core, not around the template's corner.</b> The core is the only
     * thing that identifies the machine, so the machine has to be free to turn while the core stays
     * put. Rotating the raw template offsets instead would move the core, and since the core is at
     * (7, 2, 8) in a 15-wide box - centred in x but one off in z - every rotation would put it
     * somewhere else, and the anchor would have to move with it.
     *
     * <p>The core maps to itself under every rotation, so {@link #originFor} needs no rotation
     * parameter and stays a plain subtraction.
     *
     * <p><b>The signs follow vanilla's convention, and that matters.</b>
     * {@code Rotation.CLOCKWISE_90.rotate(Direction.NORTH)} is {@code EAST}, so a northward step is
     * {@code (0, -1)} in x/z and becomes {@code (1, 0)}:
     *
     * <pre>
     * CLOCKWISE_90         (x, z) -&gt; (-z,  x)
     * CLOCKWISE_180        (x, z) -&gt; (-x, -z)
     * COUNTERCLOCKWISE_90  (x, z) -&gt; ( z, -x)
     * </pre>
     *
     * Getting these backwards would not fail loudly: a machine placed turned one way would simply
     * never be recognised. {@code rotatedPlacementIsRecognised} is the test that pins it down.
     */
    public BlockPos offsetFor(BlockPos templateOffset, Rotation rotation) {
        if (rotation == Rotation.NONE) {
            return templateOffset;
        }

        int x = templateOffset.getX() - coreOffset.getX();
        int z = templateOffset.getZ() - coreOffset.getZ();

        int rx;
        int rz;
        switch (rotation) {
            case CLOCKWISE_90 -> {
                rx = -z;
                rz = x;
            }
            case CLOCKWISE_180 -> {
                rx = -x;
                rz = -z;
            }
            case COUNTERCLOCKWISE_90 -> {
                rx = z;
                rz = -x;
            }
            default -> {
                rx = x;
                rz = z;
            }
        }

        return new BlockPos(coreOffset.getX() + rx, templateOffset.getY(), coreOffset.getZ() + rz);
    }

    /**
     * Derives one of the earlier states from the complete template.
     *
     * <p>Two changes below {@link Generation#COMPLETE}, and a third only for
     * {@link Generation#PRIMAL}: motors become disguised ones, and the motor at
     * {@link #DISPUTED_MOTOR} is dropped. The core becomes a chest only in the state the player
     * builds first - after that the core is standing there and must be expected.
     *
     * <p><b>Doing this in memory rather than shipping more .nbt files is deliberate.</b> Files
     * could drift - one regenerated, the others forgotten - and the failure would be a machine that
     * builds one way and validates another. Derived, they cannot disagree.
     */
    private static List<Entry> derive(List<Entry> complete, Generation generation) {
        List<Entry> derived = new ArrayList<>(complete.size());

        for (Entry entry : complete) {
            if (entry.offset().equals(DISPUTED_MOTOR) && generation != Generation.COMPLETE) {
                continue;
            }

            BlockState state = entry.state();
            if (state.is(AllBlocks.CREATIVE_MOTOR.get())) {
                derived.add(new Entry(entry.offset(), disguisedLike(state)));
            } else if (state.is(CEBlocks.ENIGMA_CORE.get()) && generation == Generation.PRIMAL) {
                derived.add(new Entry(entry.offset(), anchorState(Generation.PRIMAL)));
            } else {
                derived.add(entry);
            }
        }

        return derived;
    }

    /**
     * A disguised motor facing whichever way the real one did.
     *
     * <p>{@code FACING} is inherited from {@code DirectionalKineticBlock} and is
     * {@code BlockStateProperties.FACING} itself, so both blocks carry the same property instance
     * and the value transfers directly.
     */
    private static BlockState disguisedLike(BlockState motor) {
        return CEBlocks.DISGUISED_MOTOR.get().defaultBlockState()
                .setValue(DirectionalKineticBlock.FACING, motor.getValue(DirectionalKineticBlock.FACING));
    }

    /** Loads on first use. Returns null - and logs once - if the template cannot be read. */
    public static EnigmaStructure get() {
        synchronized (EnigmaStructure.class) {
            if (!loadAttempted) {
                loadAttempted = true;
                instance = load();
            }
            return instance;
        }
    }

    private static EnigmaStructure load() {
        try (InputStream in = EnigmaStructure.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                LOGGER.error("Enigma structure template is missing from the jar: {}", RESOURCE);
                return null;
            }

            CompoundTag root = NbtIo.readCompressed(in, NbtAccounter.unlimitedHeap());

            ListTag sizeTag = root.getList("size", Tag.TAG_INT);
            Vec3i size = new Vec3i(sizeTag.getInt(0), sizeTag.getInt(1), sizeTag.getInt(2));

            HolderGetter<Block> blockLookup = BuiltInRegistries.BLOCK.asLookup();

            ListTag paletteTag = root.getList("palette", Tag.TAG_COMPOUND);
            List<BlockState> palette = new ArrayList<>(paletteTag.size());
            for (int i = 0; i < paletteTag.size(); i++) {
                palette.add(NbtUtils.readBlockState(blockLookup, paletteTag.getCompound(i)));
            }

            ListTag blocksTag = root.getList("blocks", Tag.TAG_COMPOUND);
            List<Entry> entries = new ArrayList<>(blocksTag.size());
            BlockPos coreOffset = null;

            for (int i = 0; i < blocksTag.size(); i++) {
                CompoundTag blockTag = blocksTag.getCompound(i);
                ListTag posTag = blockTag.getList("pos", Tag.TAG_INT);
                BlockPos offset = new BlockPos(posTag.getInt(0), posTag.getInt(1), posTag.getInt(2));
                BlockState state = palette.get(blockTag.getInt("state"));

                if (state.isAir()) {
                    continue;
                }
                entries.add(new Entry(offset, state));
                if (state.is(CEBlocks.ENIGMA_CORE.get())) {
                    coreOffset = offset;
                }
            }

            if (coreOffset == null) {
                LOGGER.error("Enigma structure template contains no {} block", CEBlocks.ENIGMA_CORE.getId());
                return null;
            }

            LOGGER.info("Enigma structure loaded: {} blocks, size {}, core at {}",
                    entries.size(), size, coreOffset);
            List<Entry> primal = derive(entries, Generation.PRIMAL);
            List<Entry> assembled = derive(entries, Generation.ASSEMBLED);
            LOGGER.info("Enigma derived states: primal {} blocks (chest), assembled {} blocks (core)",
                    primal.size(), assembled.size());
            return new EnigmaStructure(size, List.copyOf(entries), List.copyOf(primal),
                    List.copyOf(assembled), coreOffset);
        } catch (Exception e) {
            LOGGER.error("Failed to read the Enigma structure template", e);
            return null;
        }
    }
}
